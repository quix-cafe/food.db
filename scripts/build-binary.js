// Build the standalone food.db executables (API + UI + embedded PGlite database) with Bun.
//
//   node scripts/build-binary.js                 # every target
//   node scripts/build-binary.js linux-x64       # just some
//
// Output: dist/food.db-<version>-<target>.tar.xz, each holding a single `food.db` executable.
// Needs Bun (bun.sh) and xz. Bun cross-compiles, so every target builds on any machine.

import { execFileSync } from 'node:child_process';
import { chmodSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const TARGETS = ['linux-x64', 'linux-arm64', 'darwin-x64', 'darwin-arm64'];

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = path.join(root, 'dist');
const version = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8')).version;
const targets = process.argv.slice(2).length ? process.argv.slice(2) : TARGETS;
for (const t of targets) if (!TARGETS.includes(t)) throw new Error(`Unknown target ${t}; use one of ${TARGETS.join(', ')}`);

const run = (cmd, args, opts) => execFileSync(cmd, args, { stdio: 'inherit', cwd: root, ...opts });
const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const full = path.join(dir, f);
  return statSync(full).isDirectory() ? walk(full) : [full];
});
const rel = (file) => path.relative(path.join(root, 'server/src'), file).split(path.sep).join('/');

// 1. The UI.
run('npm', ['run', 'build']);

// 2. A module that embeds the UI, the migrations and PGlite's runtime files in the binary.
const pglite = path.dirname(createRequire(path.join(root, 'server/package.json')).resolve('@electric-sql/pglite'));
const lines = [];
const imp = (file, type) => {
  const name = `f${lines.length}`;
  lines.push(`import ${name} from ${JSON.stringify(rel(file).startsWith('.') ? rel(file) : `./${rel(file)}`)} with { type: '${type}' };`);
  return name;
};
const clientDir = path.join(root, 'client/dist');
const client = walk(clientDir).map((f) => `    ${JSON.stringify('/' + path.relative(clientDir, f).split(path.sep).join('/'))}: ${imp(f, 'file')},`);
const migrations = readdirSync(path.join(root, 'server/migrations')).filter((f) => f.endsWith('.sql')).sort()
  .map((f) => `    { name: ${JSON.stringify(f)}, sql: ${imp(path.join(root, 'server/migrations', f), 'text')} },`);
const asset = (f) => imp(path.join(pglite, f), 'file');
const pgliteFiles = `{ wasm: ${asset('pglite.wasm')}, initdb: ${asset('initdb.wasm')}, data: ${asset('pglite.data')}, pg_trgm: ${asset('pg_trgm.tar.gz')} }`;
writeFileSync(path.join(root, 'server/src/embedded.gen.js'), `// Generated by scripts/build-binary.js; not checked in.
${lines.join('\n')}

export const version = ${JSON.stringify(version)};
export const files = {
  client: {
${client.join('\n')}
  },
  migrations: [
${migrations.join('\n')}
  ],
  pglite: ${pgliteFiles},
};
`);

// 3. One executable per target, packed as .tar.xz: keeps the executable bit, and xz -9e
//    makes the download about a third smaller than gzip.
mkdirSync(dist, { recursive: true });
for (const target of targets) {
  const dir = path.join(dist, target);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir);
  const exe = path.join(dir, 'food.db');
  run('bun', ['build', 'server/src/standalone.js', '--compile', '--minify', `--target=bun-${target}`,
    '--external', 'pg-native', '--outfile', exe]);
  chmodSync(exe, 0o755);
  const archive = path.join(dist, `food.db-${version}-${target}.tar.xz`);
  run('tar', ['-cJf', archive, '-C', dir, 'food.db'], { env: { ...process.env, XZ_OPT: '-9e -T0' } });
  const mb = (f) => `${(statSync(f).size / 1e6).toFixed(1)} MB`;
  console.log(`${target}: ${mb(exe)} executable, ${mb(archive)} download`);
}
